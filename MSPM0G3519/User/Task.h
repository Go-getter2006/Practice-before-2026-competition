#ifndef TASK_H
#define TASK_H

#include <stdint.h>

/* Task1 最近一次收到的 Maixcam 图像编号，0 表示尚未收到有效编号。 */
extern volatile uint8_t image;

/*******************************************************************************
 * 名    称：task1
 * 功    能：执行任务一，通过调试串口发送任务执行提示。
 * 参    数：无。
 * 出    口：无返回值。
 *******************************************************************************/
void task1(void);

/*******************************************************************************
 * 名    称：task2
 * 功    能：执行任务二，点亮 L1 指示灯。
 * 参    数：无。
 * 出    口：无返回值。
 *******************************************************************************/
void task2(void);

/*******************************************************************************
 * 名    称：task3
 * 功    能：执行任务三，熄灭 L1 指示灯。
 * 参    数：无。
 * 出    口：无返回值。
 *******************************************************************************/
void task3(void);

/*******************************************************************************
 * 名    称：Task_Process
 * 功    能：读取并执行串口屏已经接收的全部待处理任务。
 * 参    数：无。
 * 出    口：无返回值。
 * 说    明：本函数应放在主循环中持续调用。
 *******************************************************************************/
void Task_Process(void);

#endif

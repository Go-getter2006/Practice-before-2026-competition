#ifndef JY901S_H
#define JY901S_H

#include <stdint.h>

/*******************************************************************************
 * JY901S 串口驱动接入说明
 *
 * 一、串口配置
 *   1. SysConfig 中串口实例名称必须为 UART_JY901S。
 *   2. 串口参数应设置为 115200 波特率、8 位数据位、1 位停止位、无校验。
 *   3. 必须开启接收中断；本驱动使用 UART_JY901S_INST 及其对应中断号。
 *
 * 二、使用方法
 *   1. 调用 SYSCFG_DL_init() 完成系统初始化后，再调用 JY901S_Init()。
 *   2. 驱动在 UART6_IRQHandler() 中自动接收并解析 0x55 0x53 角度数据帧。
 *   3. 可直接读取 JY901S_Angles，或调用 JY901S_GetAngles() 获取三个欧拉角。
 *   4. JY901S_HasValidData() 返回 1 后，角度数据才是通过校验的有效数据。
 *
 * 三、注意事项
 *   1. 角度单位均为度，典型范围为 -180.0 至 180.0。
 *   2. JY901S_SetZeroRef() 内含阻塞延时，只能在普通程序流程中调用，禁止在中断中调用。
 *   3. 若重新生成 SysConfig，请保持 UART_JY901S 名称不变。
 *******************************************************************************/

/* JY901S 输出的欧拉角数据，单位为度。 */
typedef struct
{
    float roll;
    float pitch;
    float yaw;
} JY901S_Angles_t;

/* 最新一帧通过校验的角度数据，由串口接收中断更新。 */
extern volatile JY901S_Angles_t JY901S_Angles;

/* 与原 JY901 参考驱动兼容的偏航角变量，单位为度。 */
extern volatile float yaw;

/*******************************************************************************
 * 名    称：JY901S_Init
 * 功    能：复位协议解析状态，清空残留接收数据并开启 JY901S 串口中断。
 * 参    数：无。
 * 出    口：无返回值。
 *******************************************************************************/
void JY901S_Init(void);

/*******************************************************************************
 * 名    称：JY901S_SetZeroRef
 * 功    能：解锁传感器，将当前姿态设置为角度零点并保存配置。
 * 参    数：无。
 * 出    口：无返回值。
 * 说    明：执行期间包含约 2.8 秒阻塞延时，传感器应保持静止。
 *******************************************************************************/
void JY901S_SetZeroRef(void);

/*******************************************************************************
 * 名    称：JY901S_RxCallback
 * 功    能：向协议解析器送入一个接收到的字节。
 * 参    数：data：串口接收到的单字节数据。
 * 出    口：无返回值。
 * 说    明：正常使用时由驱动中断自动调用，也可用于轮询接收或协议测试。
 *******************************************************************************/
void JY901S_RxCallback(uint8_t data);

/*******************************************************************************
 * 名    称：JY901S_GetAngles
 * 功    能：读取最近一次通过校验的横滚角、俯仰角和偏航角。
 * 参    数：angles：用于接收角度数据的结构体指针。
 * 出    口：uint8_t，读取成功返回 1，指针为空返回 0。
 *******************************************************************************/
uint8_t JY901S_GetAngles(JY901S_Angles_t *angles);

/*******************************************************************************
 * 名    称：JY901S_HasValidData
 * 功    能：判断是否已经接收到至少一帧通过校验的角度数据。
 * 参    数：无。
 * 出    口：uint8_t，有有效数据返回 1，否则返回 0。
 *******************************************************************************/
uint8_t JY901S_HasValidData(void);

#endif

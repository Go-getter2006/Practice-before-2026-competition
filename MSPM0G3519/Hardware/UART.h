#ifndef UART_H
#define UART_H

#include <stdint.h>

/*******************************************************************************
 * 名    称： UART0_Init
 * 功    能：初始化 UART0 调试串口中断。
 * 参    数：无。
 * 出    口：无返回值。
 *******************************************************************************/
void UART0_Init(void);

/*******************************************************************************
 * 名    称： UART0_SendByte
 * 功    能：通过 UART0 发送单个字节。
 * 参    数：byte：待发送字节。
 * 出    口：无返回值。
 *******************************************************************************/
void UART0_SendByte(uint8_t byte);

/*******************************************************************************
 * 名    称： UART0_SendString
 * 功    能：通过 UART0 发送字符串。
 * 参    数：str：字符串指针。
 * 出    口：无返回值。
 *******************************************************************************/
void UART0_SendString(const char *str);

/*******************************************************************************
 * 名    称： UART0_SendInt32
 * 功    能：通过 UART0 发送有符号 32 位整数的十进制文本。
 * 参    数：value：需要发送的整数。
 * 出    口：无返回值。
 *******************************************************************************/
void UART0_SendInt32(int32_t value);

/*******************************************************************************
 * 名    称： UART0_SendFloat2
 * 功    能：通过 UART0 发送保留两位小数的浮点数文本，避免使用 sprintf。
 * 参    数：value：需要发送的浮点数。
 * 出    口：无返回值。
 *******************************************************************************/
void UART0_SendFloat2(float value);

/*******************************************************************************
 * 名    称： UART_Machine_SendByte
 * 功    能：通过 UART_Machine 发送单个字节。
 * 参    数：byte：待发送字节。
 * 出    口：无返回值。
 * 说    明：UART_Machine 的波特率和引脚由 SysConfig 统一配置。
 *******************************************************************************/
void UART_Machine_SendByte(uint8_t byte);

/*******************************************************************************
 * 名    称： UART_Machine_SendData
 * 功    能：通过 UART_Machine 阻塞发送一段二进制数据。
 * 参    数：data：待发送数据缓冲区；length：待发送字节数。
 * 出    口：无返回值。
 * 说    明：data 为空指针或 length 为 0 时不发送数据。
 *******************************************************************************/
void UART_Machine_SendData(const uint8_t *data, uint32_t length);

/*******************************************************************************
 * 名    称： UART_Bluetooth_SendData
 * 功    能：通过 UART_Bluetooth 阻塞发送一段二进制数据。
 * 参    数：data：待发送数据缓冲区；length：待发送字节数。
 * 出    口：无返回值。
 ******************************************************************************/
void UART_Bluetooth_SendData(const uint8_t *data, uint32_t length);

#endif

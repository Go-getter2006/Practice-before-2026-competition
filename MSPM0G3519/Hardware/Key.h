#ifndef KEY_H
#define KEY_H

#include <stdint.h>

/*******************************************************************************
 * 按键编号。
 * 说    明：KEY_NUM_NONE 表示没有按键事件；新增按键时，请在
 *           KEY_NUM_COUNT 前继续添加编号，并同步扩展 Key.c 中的配置。
 ******************************************************************************/
#define KEY_NUM_NONE               (0U)
#define KEY_NUM_USER               (1U)
#define KEY_NUM_COUNT              (2U)

/*******************************************************************************
 * 按键扫描参数。
 * 说    明：Key_Tick 每 10ms 调用一次，连续稳定 20ms 后确认状态变化。
 ******************************************************************************/
#define KEY_TICK_PERIOD_MS         (10U)
#define KEY_DEBOUNCE_TIME_MS       (20U)

/*******************************************************************************
 * 名    称： Key_Init
 * 功    能：初始化按键软件状态，并清除尚未读取的按键事件。
 * 说    明：必须在 SYSCFG_DL_init() 之后调用。
 * 参    数：无。
 * 出    口：无返回值。
 ******************************************************************************/
void Key_Init(void);

/*******************************************************************************
 * 名    称： Key_GetNum
 * 功    能：读取一次按键按下事件。
 * 说    明：事件读取后自动清除；没有事件时返回 KEY_NUM_NONE。
 * 参    数：无。
 * 出    口：按键编号。
 ******************************************************************************/
uint8_t Key_GetNum(void);

/*******************************************************************************
 * 名    称： Key_IsPressed
 * 功    能：读取指定按键当前的原始按下状态。
 * 说    明：所有按键均为上拉输入，低电平表示按下。
 * 参    数：keyNum：需要读取的按键编号。
 * 出    口：1 表示按下，0 表示松开或编号无效。
 ******************************************************************************/
uint8_t Key_IsPressed(uint8_t keyNum);

/*******************************************************************************
 * 名    称： Key_GetUserState
 * 功    能：读取 USER 按键当前的原始按下状态。
 * 参    数：无。
 * 出    口：1 表示按下，0 表示松开。
 ******************************************************************************/
uint8_t Key_GetUserState(void);

/*******************************************************************************
 * 名    称： Key_GetState
 * 功    能：读取当前处于按下状态的按键编号。
 * 说    明：多个按键同时按下时，返回编号最小的按键。
 * 参    数：无。
 * 出    口：按键编号；没有按键按下时返回 KEY_NUM_NONE。
 ******************************************************************************/
uint8_t Key_GetState(void);

/*******************************************************************************
 * 名    称： Key_Tick
 * 功    能：执行一次非阻塞按键扫描和消抖处理。
 * 说    明：需要每隔 KEY_TICK_PERIOD_MS 调用一次，不可在本函数中延时。
 * 参    数：无。
 * 出    口：无返回值。
 ******************************************************************************/
void Key_Tick(void);

#endif

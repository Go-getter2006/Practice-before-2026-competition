#ifndef GREYSCALE_H
#define GREYSCALE_H

#include <stdint.h>

/*******************************************************************************
 * 八路灰度传感器参数。
 * 说    明：通道编号范围为 0～7，共使用 AD0、AD1、AD2 三根通道选择线。
 ******************************************************************************/
#define GRAYSCALE_SENSOR_CHANNELS 8U

/*******************************************************************************
 * 全局巡线误差。
 * 说    明：正值表示小车右偏，负值表示小车左偏。
 ******************************************************************************/
extern float error;

/*******************************************************************************
 * 名    称： Grayscale_Sensor_Init
 * 功    能：初始化灰度传感器的通道选择状态。
 * 说    明：必须在 SYSCFG_DL_init() 之后调用，初始化后默认选择通道 0。
 * 参    数：无。
 * 出    口：无返回值。
 ******************************************************************************/
void Grayscale_Sensor_Init(void);

/*******************************************************************************
 * 名    称： Grayscale_Sensor_Read_All
 * 功    能：依次读取八路灰度传感器 OUT 引脚的高低电平。
 * 说    明：通道 0～7 的读取结果依次保存到 sensor_values[0]～[7]；
 *           高电平保存为 1，低电平保存为 0。
 * 参    数：sensor_values：至少包含 8 个 uint16_t 元素的数组。
 * 出    口：无返回值；sensor_values 为空指针时不执行读取。
 ******************************************************************************/
void Grayscale_Sensor_Read_All(uint16_t* sensor_values);

/*******************************************************************************
 * 名    称： Grayscale_Sensor_Read_Single
 * 功    能：读取指定灰度传感器通道 OUT 引脚的高低电平。
 * 参    数：channel：灰度传感器通道编号，范围为 0～7。
 * 出    口：高电平返回 1，低电平或通道编号无效时返回 0。
 ******************************************************************************/
uint16_t Grayscale_Sensor_Read_Single(uint8_t channel);

/*******************************************************************************
 * 名    称： Get_Grayscale_State
 * 功    能：读取八路灰度传感器，并组合为一个 8 位状态值。
 * 说    明：通道 0 对应 bit7，通道 7 对应 bit0。
 * 参    数：无。
 * 出    口：八路灰度传感器的组合状态。
 ******************************************************************************/
uint8_t Get_Grayscale_State(void);

/*******************************************************************************
 * 名    称： Track_err
 * 功    能：根据八路灰度传感器状态计算巡线误差。
 * 说    明：无法识别当前状态时保留上一次有效误差，避免误差突然归零。
 * 参    数：state：八路灰度传感器的组合状态。
 * 出    口：当前巡线误差；正值表示右偏，负值表示左偏。
 ******************************************************************************/
float Track_err(uint8_t state);

#endif

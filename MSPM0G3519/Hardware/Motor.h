#ifndef MOTOR_H
#define MOTOR_H

#include <stdint.h>

/*******************************************************************************
 * 模块名称：直流电机驱动与编码器采样
 * 硬件平台：TB6612FNG 双路直流电机驱动器
 * 通道映射：
 *   左轮（A 通道）：AIN1、AIN2 控制方向，PWMA 连接 TIMA0_CC0。
 *   右轮（B 通道）：BIN1、BIN2 控制方向，PWMB 连接 TIMA0_CC1。
 * 控制约定：
 *   驱动指令为正数时电机正转，为负数时电机反转，为零时短刹车。
 *   指令绝对值表示 PWM 有效占空比，范围为 0～MOTOR_PWM_MAX。
 *******************************************************************************/

/* PWM 周期计数值，也是电机驱动指令绝对值的最大值。 */
#define MOTOR_PWM_MAX                       (800)

/* 编码器速度采样周期，单位为毫秒。 */
#define MOTOR_ENCODER_SAMPLE_PERIOD_MS      (20U)

/*
 * 编码器及减速箱参数：编码器每转 13 线，A、B 两相均使用 GPIO 上升沿
 * 中断，因此每个编码器周期产生两个计数。减速比为 1∶28，车轮输出轴
 * 每转产生 13 × 2 × 28 = 728 个计数。
 */
#define MOTOR_ENCODER_LINES_PER_REV         (13U)
#define MOTOR_QEI_MULTIPLIER                (2U)
#define MOTOR_GEAR_RATIO                    (28U)
#define MOTOR_COUNTS_PER_WHEEL_REV          (MOTOR_ENCODER_LINES_PER_REV * \
                                             MOTOR_QEI_MULTIPLIER * \
                                             MOTOR_GEAR_RATIO)

/* 将一个采样周期内的单个 QEI 增量计数换算为轮端转速，单位为转/分。 */
#define MOTOR_RPM_PER_SAMPLE_COUNT          (60000.0f / \
                                             ((float)MOTOR_COUNTS_PER_WHEEL_REV * \
                                              (float)MOTOR_ENCODER_SAMPLE_PERIOD_MS))

/* 最近一个采样周期内的左右轮有符号 QEI 增量计数。 */
extern volatile int16_t Motor_LeftSpeed;
extern volatile int16_t Motor_RightSpeed;

/* 自 Motor_Init() 执行后累计的左右轮有符号 QEI 计数。 */
extern volatile int32_t Motor_LeftEncoderTotal;
extern volatile int32_t Motor_RightEncoderTotal;

#if 0
/* QEI 方向变化中断次数，用于对照 TI 例程进行硬件调试。 */
extern volatile uint32_t Motor_LeftDirectionChanges;
extern volatile uint32_t Motor_RightDirectionChanges;
#endif

/* GPIO 编码器中断使用的周期计数和累计计数。 */
extern volatile int32_t Encoder_Left_Count;
extern volatile int32_t Encoder_Right_Count;
extern volatile int32_t Get_Encoder_countA;
extern volatile int32_t Get_Encoder_countB;

/*******************************************************************************
 * 函数名称：Motor_Init
 * 功    能：初始化 TB6612 方向控制状态、停止两路电机并清零编码器数据。
 * 调用要求：必须在 SYSCFG_DL_init() 之后调用。
 * 参    数：无。
 * 返 回 值：无。
 *******************************************************************************/
void Motor_Init(void);

/*******************************************************************************
 * 函数名称：Motor_SetLeft
 * 功    能：设置左轮电机的驱动方向和 PWM 有效占空比。
 * 控制逻辑：speed > 0 时 AIN1=1、AIN2=0；speed < 0 时 AIN1=0、AIN2=1；
 *           speed = 0 时 AIN1=0、AIN2=0，电机进入短刹车状态。
 * 参    数：speed：左轮驱动指令，范围为 -MOTOR_PWM_MAX～MOTOR_PWM_MAX；
 *           超出范围的值会被限幅。
 * 返 回 值：无。
 *******************************************************************************/
void Motor_SetLeft(int16_t speed);

/*******************************************************************************
 * 函数名称：Motor_SetRight
 * 功    能：设置右轮电机的驱动方向和 PWM 有效占空比。
 * 控制逻辑：speed > 0 时 BIN1=1、BIN2=0；speed < 0 时 BIN1=0、BIN2=1；
 *           speed = 0 时 BIN1=0、BIN2=0，电机进入短刹车状态。
 * 参    数：speed：右轮驱动指令，范围为 -MOTOR_PWM_MAX～MOTOR_PWM_MAX；
 *           超出范围的值会被限幅。
 * 返 回 值：无。
 *******************************************************************************/
void Motor_SetRight(int16_t speed);

/*******************************************************************************
 * 函数名称：Motor_SetSpeed
 * 功    能：同时设置左右轮电机的驱动指令。
 * 参    数：left：左轮驱动指令；right：右轮驱动指令；两者的有效范围均为
 *           -MOTOR_PWM_MAX～MOTOR_PWM_MAX。
 * 返 回 值：无。
 *******************************************************************************/
void Motor_SetSpeed(int16_t left, int16_t right);

/*******************************************************************************
 * 函数名称：Motor_Forward
 * 功    能：控制小车以指定 PWM 幅值前进。
 * 说    明：由于左右电机镜像安装，前进时左轮使用正向指令，右轮使用反向指令。
 * 参    数：speed：PWM 幅值，范围为 0～MOTOR_PWM_MAX。
 * 返 回 值：无。
 *******************************************************************************/
void Motor_Forward(uint16_t speed);

/*******************************************************************************
 * 函数名称：Motor_Backward
 * 功    能：控制小车以指定 PWM 幅值后退。
 * 说    明：由于左右电机镜像安装，后退时左轮使用反向指令，右轮使用正向指令。
 * 参    数：speed：PWM 幅值，范围为 0～MOTOR_PWM_MAX。
 * 返 回 值：无。
 *******************************************************************************/
void Motor_Backward(uint16_t speed);

/*******************************************************************************
 * 函数名称：Motor_Stop
 * 功    能：将两路 PWM 有效占空比清零，并使左右轮进入短刹车状态。
 * 参    数：无。
 * 返 回 值：无。
 *******************************************************************************/
void Motor_Stop(void);

/*******************************************************************************
 * 函数名称：Motor_EncoderTick
 * 功    能：保存并清零 GPIO 中断累计的左右编码器周期计数。
 * 调用周期：20 ms，由 TIMA1 定时中断调用，普通程序不应重复调用。
 * 参    数：无。
 * 返 回 值：无。
 *******************************************************************************/
void Motor_EncoderTick(void);

/*******************************************************************************
 * 函数名称：Motor_GetSpeed_Left
 * 功    能：读取左轮最近一个采样周期内的有符号编码器增量计数。
 * 参    数：无。
 * 返 回 值：左轮 QEI 增量计数。
 *******************************************************************************/
int16_t Motor_GetSpeed_Left(void);

/*******************************************************************************
 * 函数名称：Motor_GetSpeed_Right
 * 功    能：读取右轮最近一个采样周期内的有符号编码器增量计数。
 * 参    数：无。
 * 返 回 值：右轮 QEI 增量计数。
 *******************************************************************************/
int16_t Motor_GetSpeed_Right(void);

/*******************************************************************************
 * 函数名称：Motor_GetSpeedRPM_Left
 * 功    能：将左轮最近一个采样周期内的 QEI 增量换算为轮端转速。
 * 参    数：无。
 * 返 回 值：左轮轮端转速，单位为转/分。
 *******************************************************************************/
float Motor_GetSpeedRPM_Left(void);

/*******************************************************************************
 * 函数名称：Motor_GetSpeedRPM_Right
 * 功    能：将右轮最近一个采样周期内的 QEI 增量换算为轮端转速。
 * 参    数：无。
 * 返 回 值：右轮轮端转速，单位为转/分。
 *******************************************************************************/
float Motor_GetSpeedRPM_Right(void);

/*******************************************************************************
 * 函数名称：Motor_GetEncoderTotal_Left
 * 功    能：读取左轮自初始化以来的有符号 QEI 累计计数。
 * 参    数：无。
 * 返 回 值：左轮 QEI 累计计数。
 *******************************************************************************/
int32_t Motor_GetEncoderTotal_Left(void);

/*******************************************************************************
 * 函数名称：Motor_GetEncoderTotal_Right
 * 功    能：读取右轮自初始化以来的有符号 QEI 累计计数。
 * 参    数：无。
 * 返 回 值：右轮 QEI 累计计数。
 *******************************************************************************/
int32_t Motor_GetEncoderTotal_Right(void);

/*******************************************************************************
 * 函数名称：Motor_ResetEncoderTotal
 * 功    能：清零 GPIO 外部中断方式的左右轮瞬时计数和累计计数。
 * 参    数：无。
 * 返 回 值：无。
 *******************************************************************************/
void Motor_ResetEncoderTotal(void);

#endif
